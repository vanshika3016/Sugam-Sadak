function getNestedTranslation(obj: Translations, path: string): string {
  return path.split('.').reduce((current: any, key: string) => current?.[key], obj) as string ?? path
}

export function useTranslation() {
  const [language, setLanguage] = useState<Language>(() => {
    if (typeof window !== 'undefined') {
      return (localStorage.getItem('sugam_sadak_lang') as Language) || 'en'
    }
    return 'en'
  })

  useEffect(() => {
    localStorage.setItem('sugam_sadak_lang', language)
  }, [language])

  const t = (key: string): string => {
    return getNestedTranslation(translations[language], key)
  }

  return { t, language, setLanguage }
}

